#!/usr/bin/env bash
# init-local-env.sh — generate .env.local from .env.example with local overrides.
#
# .env.example is the single source of truth for the variable list; this script
# only replaces values that must differ on a developer machine. Every override
# key must exist in .env.example — otherwise the script fails (catches drift).
#
# Usage: scripts/init-local-env.sh [--force]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/.env.example"
DST="${LOCAL_ENV_FILE:-$ROOT/.env.local}"

# Local overrides — KEY=VALUE, one per line.
OVERRIDES='
CERTBOT_EMAIL=local@localhost
NGINX_SSL_CERT_PATH=/etc/nginx/ssl/cert.pem
NGINX_SSL_KEY_PATH=/etc/nginx/ssl/key.pem
NGINX_SSL_CHAIN_PATH=/etc/nginx/ssl/ca.pem
NGINX_UPSTREAM_HOST=go-gateway
NGINX_UPSTREAM_PORT=80
NGINX_LB_ALGORITHM=
NGINX_RATE_LIMIT_RATE=1000r/m
NGINX_RATE_LIMIT_AUTH_RATE=100r/m
NGINX_RATE_LIMIT_GENERAL_RATE=2000r/m
'

if [ -e "$DST" ] && [ "${1:-}" != "--force" ]; then
    echo "$DST already exists — leaving it untouched (use --force to regenerate)."
    exit 0
fi

# Fail on override keys missing from .env.example
missing=0
while IFS='=' read -r key _; do
    [ -z "$key" ] && continue
    if ! grep -q "^${key}=" "$SRC"; then
        echo "error: override key '$key' is not defined in .env.example" >&2
        missing=1
    fi
done <<< "$OVERRIDES"
[ "$missing" -eq 0 ] || exit 1

{
    echo "# GENERATED by scripts/init-local-env.sh from .env.example — local machine only."
    echo "# Regenerate: scripts/init-local-env.sh --force"
    OVERRIDES="$OVERRIDES" awk '
        BEGIN {
            n = split(ENVIRON["OVERRIDES"], lines, "\n")
            for (i = 1; i <= n; i++) {
                if (lines[i] == "") continue
                eq = index(lines[i], "=")
                ov[substr(lines[i], 1, eq - 1)] = substr(lines[i], eq + 1)
            }
        }
        /^[A-Za-z_][A-Za-z0-9_]*=/ {
            key = substr($0, 1, index($0, "=") - 1)
            if (key in ov) { print key "=" ov[key]; next }
        }
        { print }
    ' "$SRC"
} > "$DST.tmp"
mv "$DST.tmp" "$DST"

echo "Generated $DST"
